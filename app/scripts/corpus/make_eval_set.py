"""Turn the downloaded Commons photos into an eval set for scripts/eval/run_eval.py.

Commons has no two photos of the same koozie, so "reshoot" queries are simulated: each catalogue
photo is re-cropped, rotated, re-lit, blurred and re-compressed. That checks robustness to camera
differences on real photos (creases, glare, clutter), which the synthetic set can't. It does NOT
replace real re-photographs; see docs/EVALUATION.md for how to collect those.

Group shots (piles of koozies) become "novel" queries: they should not match any single item.

Usage:  python -I scripts/corpus/make_eval_set.py
        python scripts/eval/run_eval.py --fixtures fixtures/web-corpus/eval
"""

from __future__ import annotations

import json
import os
import random

from PIL import Image, ImageEnhance, ImageFilter

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "fixtures", "web-corpus")
OUT = os.path.join(SRC, "eval")

# Photos showing several different koozies at once (judged by eye).
GROUP_SHOTS = ("2nd-annual-young-at-heart", "daily-waters-pub", "maine-cabin-junk-drawer", "nola-koozies")
VARIANTS = 2


def reshoot(im: Image.Image, rng: random.Random) -> Image.Image:
    w, h = im.size
    s = rng.uniform(0.72, 0.9)
    cw, ch = int(w * s), int(h * s)
    x, y = rng.randint(0, w - cw), rng.randint(0, h - ch)
    out = im.crop((x, y, x + cw, y + ch)).rotate(rng.uniform(-9, 9), resample=Image.BICUBIC, expand=False, fillcolor=(90, 90, 90))
    out = ImageEnhance.Brightness(out).enhance(rng.uniform(0.75, 1.25))
    out = ImageEnhance.Contrast(out).enhance(rng.uniform(0.8, 1.2))
    out = ImageEnhance.Color(out).enhance(rng.uniform(0.75, 1.2))
    # White-balance shift.
    r, g, b = out.split()
    r = r.point(lambda v, k=rng.uniform(0.9, 1.1): min(255, int(v * k)))
    b = b.point(lambda v, k=rng.uniform(0.9, 1.1): min(255, int(v * k)))
    out = Image.merge("RGB", (r, g, b))
    if rng.random() < 0.6:
        out = out.filter(ImageFilter.GaussianBlur(rng.uniform(0.4, 1.4)))
    out.thumbnail((900, 900))
    return out


def main():
    manifest = json.load(open(os.path.join(SRC, "manifest.json"), encoding="utf8"))
    os.makedirs(os.path.join(OUT, "images"), exist_ok=True)
    rng = random.Random(7)
    catalog, queries = [], []
    for f in manifest["files"]:
        name = f["file"]
        key = name.removesuffix(".jpg")
        im = Image.open(os.path.join(SRC, "images", name)).convert("RGB")
        if name.startswith(GROUP_SHOTS):
            qn = f"q-novel-{key}.jpg"
            reshoot(im, rng).save(os.path.join(OUT, "images", qn), quality=80)
            queries.append({"file": qn, "item": None, "kind": "novel", "source": f["page"]})
            continue
        cn = f"cat-{key}.jpg"
        im.save(os.path.join(OUT, "images", cn), quality=88)
        catalog.append({"key": key, "description": f["title"].removeprefix("File:"), "photos": [cn], "source": f["page"], "licence": f["licence"]})
        for v in range(VARIANTS):
            qn = f"q-reshoot-{key}-{v}.jpg"
            reshoot(im, rng).save(os.path.join(OUT, "images", qn), quality=rng.randint(68, 85))
            queries.append({"file": qn, "item": key, "kind": "reshoot"})
    json.dump(
        {"note": "Generated by scripts/corpus/make_eval_set.py from openly licensed Commons photos; see ../manifest.json for attribution.", "catalog": catalog, "queries": queries},
        open(os.path.join(OUT, "manifest.json"), "w", encoding="utf8"),
        indent=1,
    )
    print(f"{len(catalog)} catalogue photos, {len(queries)} queries -> {OUT}")


if __name__ == "__main__":
    main()
